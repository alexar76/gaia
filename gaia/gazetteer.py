#: Abbreviations expanded on the query side only ("St. Petersburg" → "Saint Petersburg").
_TOKEN_VARIANTS = {"st": ("saint",), "ste": ("sainte",), "mt": ("mount",), "ft": ("fort",),
                   "pt": ("port", "point")}

_PUNCT = re.compile(r"[\s\-‐‑‒–—―'’ʼ`´.·,()/\\\"«»“”]+")


def norm(text: Any) -> str:
    """The lookup key: case-folded, accents dropped, punctuation turned into spaces.

    Index and query go through the same function, so "São Paulo" = "sao paulo" =
    "SAO-PAULO", and "Нью-Йорк" = "нью йорк" (й loses its breve on both sides alike).
    """
    t = unicodedata.normalize("NFKD", str(text)).casefold()
    t = "".join(ch for ch in t if not unicodedata.combining(ch))
    return " ".join(_PUNCT.sub(" ", t).split())


def _variants(key: str) -> list[str]:
    out = [key]
    tokens = key.split(" ")
    for i, tok in enumerate(tokens):
        for alt in _TOKEN_VARIANTS.get(tok, ()):
            for base in list(out):
                parts = base.split(" ")
                if i < len(parts) and parts[i] == tok:
                    parts[i] = alt
                    out.append(" ".join(parts))
    return list(dict.fromkeys(out))


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * 6371.0088 * math.asin(min(1.0, math.sqrt(h)))


@dataclass(frozen=True)
class Place:
    geonameid: int
    name: str
    latitude: float
    longitude: float
    country_code: str
    country: str
    admin1_code: str
    admin1: str
    population: int
    timezone: str
    feature_code: str

    @property
    def label(self) -> str:
        parts = [self.name]
        if self.admin1 and self.admin1 != self.name:
            parts.append(self.admin1)
        parts.append(self.country_code)
        return ", ".join(parts)

    def as_dict(self) -> dict[str, Any]:
        return {**asdict(self), "label": self.label}


@dataclass
class Resolution:
    query: str
    chosen: Place | None
    candidates: list[Place] = field(default_factory=list)
    ambiguous: bool = False
    reason: str = ""

    def as_dict(self, limit: int = 5) -> dict[str, Any]:
        return {
            "query": self.query,
            "chosen": self.chosen.as_dict() if self.chosen else None,
            "ambiguous": self.ambiguous,
            "reason": self.reason,
            "candidates": [c.as_dict() for c in self.candidates[:limit]],
        }


class GazetteerError(ValueError):
    """A name GAIA cannot turn into one place — the message says what to send instead."""


# ── Building ──────────────────────────────────────────────────────────────────


def _load_country_names() -> dict[str, list[str]]:
    try:
        return json.loads(_COUNTRY_NAMES.read_text(encoding="utf-8"))["names"]
    except (OSError, ValueError, KeyError):
        return {}


def _rows(text: str) -> Iterable[list[str]]:
    for line in text.splitlines():
        if line and not line.startswith("#"):
            yield line.split("\t")


def build(out_path: str | Path, *, cities: str, admin1: str, countries: str,
          meta: dict[str, str] | None = None) -> dict[str, int]:
    """Write the SQLite gazetteer from the three GeoNames texts. Returns row counts.

    Written to ``<out>.tmp`` and renamed, so a reader never opens a half-built file.
    """
    out = Path(out_path)
    tmp = out.with_suffix(out.suffix + ".tmp")
    if tmp.exists():
        tmp.unlink()
    db = sqlite3.connect(tmp)
    db.executescript("""
        PRAGMA journal_mode = OFF;
        PRAGMA synchronous = OFF;
        CREATE TABLE place (id INTEGER PRIMARY KEY, name TEXT NOT NULL, lat REAL NOT NULL,
            lon REAL NOT NULL, fcode TEXT, cc TEXT, a1 TEXT, pop INTEGER, tz TEXT,
            latb INTEGER, lonb INTEGER);
        CREATE TABLE name (key TEXT NOT NULL, id INTEGER NOT NULL, alt INTEGER NOT NULL,
            PRIMARY KEY (key, id)) WITHOUT ROWID;
        CREATE TABLE country (cc TEXT PRIMARY KEY, iso3 TEXT, name TEXT) WITHOUT ROWID;
        CREATE TABLE country_key (key TEXT NOT NULL, cc TEXT NOT NULL,
            PRIMARY KEY (key, cc)) WITHOUT ROWID;
        CREATE TABLE admin1 (cc TEXT NOT NULL, a1 TEXT NOT NULL, name TEXT,
            PRIMARY KEY (cc, a1)) WITHOUT ROWID;
        CREATE TABLE admin1_key (key TEXT NOT NULL, cc TEXT NOT NULL, a1 TEXT NOT NULL,
            PRIMARY KEY (key, cc, a1)) WITHOUT ROWID;
        CREATE TABLE meta (k TEXT PRIMARY KEY, v TEXT) WITHOUT ROWID;
    """)

    # Countries: ISO2, ISO3, the GeoNames English name, CLDR names, everyday aliases.
    country_keys: set[tuple[str, str]] = set()
    n_countries = 0
    for r in _rows(countries):
        if len(r) < 5 or len(r[0]) != 2:
            continue
        cc, iso3, name = r[0].upper(), r[1].upper(), r[4]
        db.execute("INSERT OR REPLACE INTO country VALUES (?,?,?)", (cc, iso3, name))
        n_countries += 1
        for k in (cc, iso3, name):
            country_keys.add((norm(k), cc))
    for cc, names in _load_country_names().items():
        for n in names:
            country_keys.add((norm(n), cc.upper()))
    for alias, cc in COUNTRY_ALIASES.items():
        country_keys.add((norm(alias), cc))
    db.executemany("INSERT OR IGNORE INTO country_key VALUES (?,?)",
                   sorted(k for k in country_keys if k[0]))

    # First-level regions: code (when it is letters — "TX", not "08"), name, ASCII name.
    admin_keys: set[tuple[str, str, str]] = set()
    by_ascii: dict[tuple[str, str], str] = {}
    n_admin = 0
    for r in _rows(admin1):
        if len(r) < 3 or "." not in r[0]:
            continue
        cc, a1 = r[0].split(".", 1)
        db.execute("INSERT OR REPLACE INTO admin1 VALUES (?,?,?)", (cc, a1, r[1]))
        n_admin += 1
        by_ascii[(cc, norm(r[2]))] = a1
        if a1.isalpha():
            admin_keys.add((norm(a1), cc, a1))
        for k in (r[1], r[2]):
            admin_keys.add((norm(k), cc, a1))
    for cc, abbreviations in ADMIN1_ABBREVIATIONS.items():
        for abbr, full in abbreviations.items():
            a1 = by_ascii.get((cc, norm(full)))
            if a1:
                admin_keys.add((norm(abbr), cc, a1))
    db.executemany("INSERT OR IGNORE INTO admin1_key VALUES (?,?,?)",
                   sorted(k for k in admin_keys if k[0]))

    # Places and every name they go by. alt=0 for the official/ASCII name, 1 otherwise.
    n_places = n_names = 0
    batch_p: list[tuple] = []
    batch_n: list[tuple] = []
    for r in _rows(cities):
        if len(r) < 18:
            continue
        try:
            gid, lat, lon = int(r[0]), float(r[4]), float(r[5])
            pop = int(r[14] or 0)
        except ValueError:
            continue
        batch_p.append((gid, r[1], lat, lon, r[7], r[8].upper(), r[10], pop, r[17],
                        math.floor(lat), math.floor(lon)))
        keys: dict[str, int] = {}
        for k in (r[1], r[2]):
            nk = norm(k)
            if nk:
                keys[nk] = 0
        for alt in r[3].split(","):
            nk = norm(alt)
            # Latin strings of two letters or fewer are codes, not names ("東京" is a name);
            # anything with a digit is a postcode or an identifier.
            if not (nk.isascii() and len(nk) <= 2) and not any(ch.isdigit() for ch in nk):
                keys.setdefault(nk, 1)
        batch_n.extend((k, gid, a) for k, a in keys.items())
        n_places += 1
        if len(batch_p) >= 20_000:
            db.executemany("INSERT OR REPLACE INTO place VALUES (?,?,?,?,?,?,?,?,?,?,?)", batch_p)
            db.executemany("INSERT OR IGNORE INTO name VALUES (?,?,?)", batch_n)
            n_names += len(batch_n)
            batch_p, batch_n = [], []
    db.executemany("INSERT OR REPLACE INTO place VALUES (?,?,?,?,?,?,?,?,?,?,?)", batch_p)
    db.executemany("INSERT OR IGNORE INTO name VALUES (?,?,?)", batch_n)
    n_names += len(batch_n)
    db.execute("CREATE INDEX place_bucket ON place (latb, lonb)")

    counts = {"places": n_places, "names": n_names, "countries": n_countries,
              "admin1": n_admin}
    info = {
        "attribution": ATTRIBUTION,
        "licence_url": LICENCE_URL,
        "built_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "country_names": json.loads(_COUNTRY_NAMES.read_text(encoding="utf-8")).get("source", "")
        if _COUNTRY_NAMES.exists() else "",
        **{f"count_{k}": str(v) for k, v in counts.items()},
        **(meta or {}),
    }
    db.executemany("INSERT OR REPLACE INTO meta VALUES (?,?)", sorted(info.items()))
    db.commit()
    db.execute("VACUUM")
    db.close()
    os.replace(tmp, out)
    return counts


def download(dest: str | Path, *, base: str = GEONAMES_BASE, timeout: float = 120.0) -> dict[str, str]:
    """Fetch the three GeoNames files into ``dest``; return ``{name: sha256}``."""
    import httpx

    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    digests: dict[str, str] = {}
    for name in GEONAMES_FILES:
        resp = httpx.get(base + name, timeout=timeout, follow_redirects=False,
                         headers={"User-Agent": "GAIA-gazetteer/1 (+https://iot.modelmarket.dev)"})
        resp.raise_for_status()
        (dest / name).write_bytes(resp.content)
        digests[name] = hashlib.sha256(resp.content).hexdigest()
    return digests


def build_from_dir(src: str | Path, out: str | Path, digests: dict[str, str] | None = None) -> dict[str, int]:
    src = Path(src)
    with zipfile.ZipFile(src / "cities1000.zip") as zf:
        cities = zf.read("cities1000.txt").decode("utf-8")
    if digests is None:
        digests = {n: hashlib.sha256((src / n).read_bytes()).hexdigest() for n in GEONAMES_FILES}
    meta = {"source": GEONAMES_BASE + "{" + ",".join(GEONAMES_FILES) + "}",
            **{f"sha256_{n}": d for n, d in digests.items()}}
    return build(out,
                 cities=cities,
                 admin1=(src / "admin1CodesASCII.txt").read_text(encoding="utf-8"),
                 countries=(src / "countryInfo.txt").read_text(encoding="utf-8"),
                 meta=meta)


