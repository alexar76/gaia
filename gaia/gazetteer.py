"""A place name → coordinates, and coordinates → the nearest place (GeoNames).

A buyer's model asks for "air in Kraków" or "Paris, Texas". GAIA used to know only the
cities it relays, so every other name was refused, and "Paris, Texas" could only be
refused, never answered. This module resolves any populated place on Earth from the
GeoNames gazetteer, in the spellings people write it in, and is honest when a name is
ambiguous instead of guessing.

**Data.** GeoNames ``cities1000`` (every place of 1,000+ people, plus seats of
government), ``admin1CodesASCII`` (states, provinces, regions) and ``countryInfo``.
Licence CC BY 4.0 — cite "GeoNames (geonames.org)". Country names in 16 languages come
from the Unicode CLDR (``country_names.json``, generated by
``scripts/gen_country_names.py``; Unicode License).

**Shape.** ``python -m gaia.gazetteer build --out PATH`` downloads the three files once
and writes a single SQLite file, with the source URLs, their SHA-256 and the build time
in a ``meta`` table — every answer can say exactly which gazetteer produced it. GAIA
opens the file read-only from ``GAIA_GAZETTEER_PATH``. Without it, GAIA resolves only
the cities it relays, exactly as before.

**Resolution rules** (``Gazetteer.resolve``):

* ``"Head, q1, q2"`` — the head is the place; each qualifier must name the candidate's
  country (ISO code or name in any of the 16 languages) or its first-level region
  (state code, name, or a common abbreviation such as ``ON`` or ``NSW``). A qualifier
  that names nothing at all is an error, not something to ignore.
* Candidates that sit within 25 km of a larger candidate in the same country are the
  same place listed twice (GeoNames keeps seats and sections apart) and are dropped.
* The largest candidate wins only when it is at least 5x the next one. Otherwise the
  name is **ambiguous** and the caller gets the candidates to choose from: answering
  Springfield, Illinois to someone who meant Springfield, Missouri under a valid
  signature is worse than asking.
"""

