class Gazetteer:
    """Read-only lookups over a built gazetteer file. Safe to share across threads."""

    def __init__(self, path: str | Path):
        self.path = str(path)
        if not Path(self.path).is_file():
            raise FileNotFoundError(self.path)
        self._local = threading.local()
        self._meta = {k: v for k, v in self._db().execute("SELECT k, v FROM meta")}
        self._countries = {cc: (iso3, name) for cc, iso3, name in
                           self._db().execute("SELECT cc, iso3, name FROM country")}
        self._admin1 = {(cc, a1): name for cc, a1, name in
                        self._db().execute("SELECT cc, a1, name FROM admin1")}
        self.resolve = lru_cache(maxsize=4096)(self._resolve)  # type: ignore[method-assign]

    def _db(self) -> sqlite3.Connection:
        conn = getattr(self._local, "conn", None)
        if conn is None:
            uri = Path(self.path).resolve().as_uri() + "?mode=ro&immutable=1"
            conn = sqlite3.connect(uri, uri=True, check_same_thread=False)
            self._local.conn = conn
        return conn

    def meta(self) -> dict[str, str]:
        return dict(self._meta)

    def provenance(self) -> dict[str, Any]:
        """What every answer cites: the data, its licence, and which build it was."""
        return {
            "source": "GeoNames cities1000 + admin1CodesASCII + countryInfo",
            "attribution": ATTRIBUTION,
            "licence_url": LICENCE_URL,
            "built_at": self._meta.get("built_at", ""),
            "sha256_cities1000": self._meta.get("sha256_cities1000.zip", ""),
            "places": int(self._meta.get("count_places", "0") or 0),
            "country_names": self._meta.get("country_names", ""),
        }

    def _place(self, row: tuple) -> Place:
        gid, name, lat, lon, fcode, cc, a1, pop, tz = row
        return Place(
            geonameid=int(gid), name=name, latitude=float(lat), longitude=float(lon),
            country_code=cc or "", country=self._countries.get(cc, ("", ""))[1],
            admin1_code=a1 or "", admin1=self._admin1.get((cc, a1), "") or "",
            population=int(pop or 0), timezone=tz or "", feature_code=fcode or "",
        )

    def _qualifier_targets(self, q: str) -> tuple[set[str], set[tuple[str, str]]]:
        key = norm(q)
        db = self._db()
        ccs = {cc for (cc,) in db.execute("SELECT cc FROM country_key WHERE key = ?", (key,))}
        a1s = {(cc, a1) for cc, a1 in db.execute(
            "SELECT cc, a1 FROM admin1_key WHERE key = ?", (key,))}
        return ccs, a1s

    def countries_named(self, text: str) -> set[str]:
        """ISO codes of the countries this text names ("Germany", "Германия", "DEU")."""
        return self._qualifier_targets(text)[0]

    def candidates(self, head: str) -> list[tuple[Place, int]]:
        keys = _variants(norm(head))
        if not keys or not keys[0]:
            return []
        marks = ",".join("?" * len(keys))
        rows = self._db().execute(
            f"SELECT p.id, p.name, p.lat, p.lon, p.fcode, p.cc, p.a1, p.pop, p.tz, MIN(n.alt) "
            f"FROM name n JOIN place p ON p.id = n.id WHERE n.key IN ({marks}) GROUP BY p.id",
            keys,
        ).fetchall()
        return [(self._place(r[:9]), int(r[9])) for r in rows]

    def _resolve(self, text: str, country: str = "") -> Resolution:
        query = " ".join(str(text).split())[:160]
        head, _, rest = query.partition(",")
        qualifiers = [q.strip() for q in rest.split(",") if q.strip()]
        if country and country.strip():
            qualifiers.append(country.strip())
        if not norm(head):
            raise GazetteerError("an empty place name: pass a city, or latitude and longitude")
        found = self.candidates(head)
        for q in qualifiers:
            ccs, a1s = self._qualifier_targets(q)
            if not ccs and not a1s:
                raise GazetteerError(
                    f"{q[:60]!r} after the comma names no country or state GeoNames knows; "
                    "write the country (\"France\", \"FR\") or the state (\"Texas\", \"TX\")"
                )
            found = [(p, alt) for p, alt in found
                     if p.country_code in ccs or (p.country_code, p.admin1_code) in a1s]
        if not found:
            where = f" in {', '.join(qualifiers)}" if qualifiers else ""
            return Resolution(query, None, [], False,
                              f"no populated place called {head.strip()[:60]!r}{where} in GeoNames "
                              "(places of 1,000+ people); pass latitude and longitude")
        # Largest first, an alternate-name match weighed down (ALT_NAME_WEIGHT).
        def weight(pa: tuple[Place, int]) -> float:
            return pa[0].population / (ALT_NAME_WEIGHT if pa[1] else 1.0)

        found.sort(key=lambda pa: (-weight(pa), pa[1], pa[0].geonameid))
        kept: list[tuple[Place, float]] = []
        for pa in found:
            place = pa[0]
            if any(k.country_code == place.country_code
                   and haversine_km(k.latitude, k.longitude, place.latitude, place.longitude)
                   < DUPLICATE_KM for k, _w in kept):
                continue
            kept.append((place, weight(pa)))
        places = [k for k, _w in kept]
        top = places[0]
        if len(kept) == 1:
            return Resolution(query, top, places, False, "only match")
        if kept[0][1] > 0 and kept[0][1] >= DOMINANCE * kept[1][1]:
            return Resolution(query, top, places, False,
                              f"largest of {len(kept)} places with this name "
                              f"(at least {DOMINANCE:g}x the next); add a country or state "
                              "after a comma for another")
        return Resolution(query, None, places, True,
                          f"{len(kept)} places called {head.strip()[:60]!r} are of comparable "
                          "size; add the state or country after a comma, e.g. "
                          f"{places[0].label!r}")

    def require(self, text: str, country: str = "") -> Place:
        """One place, or a GazetteerError that lists what the caller could send instead."""
        res = self.resolve(text, country)
        if res.chosen is not None:
            return res.chosen
        if res.ambiguous:
            options = "; ".join(f"{p.label} (pop {p.population:,})" for p in res.candidates[:5])
            raise GazetteerError(f"{text.strip()[:80]!r} is ambiguous — {options}. "
                                 "Add the state or country after a comma.")
        raise GazetteerError(res.reason)

    def nearest(self, lat: float, lon: float, *, limit: int = 3,
                max_km: float = REVERSE_MAX_KM, min_population: int = 0,
                include_sections: bool = False) -> list[tuple[Place, float]]:
        """Populated places nearest a point, closest first, none farther than max_km.

        City sections (SECTION_CODES) are skipped unless include_sections is set.
        """
        if not (-90.0 <= lat <= 90.0 and -180.0 <= lon <= 180.0):
            raise GazetteerError("latitude must be in [-90, 90] and longitude in [-180, 180]")
        max_km = min(float(max_km), REVERSE_MAX_KM)
        lat_span = math.ceil(max_km / 111.0)
        coslat = max(math.cos(math.radians(min(abs(lat) + lat_span, 89.9))), 1e-3)
        lon_span = min(180, math.ceil(max_km / (111.32 * coslat)))
        lat0, lon0 = math.floor(lat), math.floor(lon)
        lats = [b for b in range(lat0 - lat_span, lat0 + lat_span + 1) if -90 <= b <= 89]
        lons = sorted({((b + 180) % 360) - 180 for b in range(lon0 - lon_span, lon0 + lon_span + 1)})
        db = self._db()
        out: list[tuple[Place, float]] = []
        for latb in lats:
            marks = ",".join("?" * len(lons))
            for row in db.execute(
                f"SELECT id, name, lat, lon, fcode, cc, a1, pop, tz FROM place "
                f"WHERE latb = ? AND lonb IN ({marks}) AND pop >= ?",
                (latb, *lons, int(min_population)),
            ):
                if not include_sections and row[4] in SECTION_CODES:
                    continue
                km = haversine_km(lat, lon, row[2], row[3])
                if km <= max_km:
                    out.append((self._place(row), km))
        out.sort(key=lambda pk: (pk[1], -pk[0].population))
        return out[: max(1, int(limit))]


_DEFAULT: Gazetteer | None = None
_DEFAULT_PATH: str | None = None
_DEFAULT_LOCK = threading.Lock()


def load_default() -> Gazetteer | None:
    """The gazetteer at GAIA_GAZETTEER_PATH, or None when unset/missing (GAIA then
    resolves only the cities it relays). Re-reads the path so tests can switch it."""
    global _DEFAULT, _DEFAULT_PATH
    path = os.environ.get("GAIA_GAZETTEER_PATH", "").strip()
    if not path:
        return None
    with _DEFAULT_LOCK:
        if _DEFAULT is not None and _DEFAULT_PATH == path:
            return _DEFAULT
        try:
            _DEFAULT = Gazetteer(path)
        except (OSError, sqlite3.Error) as exc:
            print(f"gazetteer: {path} unusable ({type(exc).__name__}: {exc}); "
                  "resolving relayed cities only", file=sys.stderr)
            _DEFAULT = None
        _DEFAULT_PATH = path
        return _DEFAULT


def _main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m gaia.gazetteer", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="download GeoNames and write the SQLite gazetteer")
    b.add_argument("--out", required=True)
    b.add_argument("--from-dir", help="use files already downloaded here instead of fetching")
    b.add_argument("--keep-dir", help="where to keep the downloaded files (default: next to --out)")
    q = sub.add_parser("query", help="resolve a name against a built gazetteer")
    q.add_argument("--db", required=True)
    q.add_argument("name", nargs="?")
    q.add_argument("--lat", type=float)
    q.add_argument("--lon", type=float)
    args = ap.parse_args(argv)
    if args.cmd == "build":
        if args.from_dir:
            counts = build_from_dir(args.from_dir, args.out)
        else:
            keep = Path(args.keep_dir or Path(args.out).parent / "geonames-src")
            digests = download(keep)
            counts = build_from_dir(keep, args.out, digests)
        size = Path(args.out).stat().st_size
        print(json.dumps({"out": args.out, "bytes": size, **counts}))
        return 0
    gz = Gazetteer(args.db)
    if args.lat is not None and args.lon is not None:
        print(json.dumps([{**p.as_dict(), "distance_km": round(km, 1)}
                          for p, km in gz.nearest(args.lat, args.lon)], ensure_ascii=False, indent=1))
    else:
        print(json.dumps(gz.resolve(args.name or "").as_dict(), ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(_main())
