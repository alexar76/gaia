GEONAMES_BASE = "https://download.geonames.org/export/dump/"
GEONAMES_FILES = ("cities1000.zip", "admin1CodesASCII.txt", "countryInfo.txt")
ATTRIBUTION = "GeoNames (geonames.org) · CC BY 4.0"
LICENCE_URL = "https://creativecommons.org/licenses/by/4.0/"

#: The largest candidate is chosen only when it is this many times the next one.
DOMINANCE = 5.0
#: Same name, same country, closer than this to a larger candidate → the same place.
DUPLICATE_KM = 25.0
#: A match on an alternate name (historic, foreign, colloquial) counts as this many times
#: smaller than the place really is. Without it "Victoria" resolved to Hong Kong, whose
#: old name it is, over every city actually called Victoria.
ALT_NAME_WEIGHT = 20.0
#: GeoNames feature codes a reverse lookup skips unless asked: sections of a city
#: ("Mitte" for a point in central Berlin) are not the place a caller is in.
SECTION_CODES = ("PPLX",)
#: A reverse lookup never names a place farther than this from the point.
REVERSE_MAX_KM = 100.0

_COUNTRY_NAMES = Path(__file__).with_name("country_names.json")

